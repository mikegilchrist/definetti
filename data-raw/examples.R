args <- commandArgs(trailingOnly = TRUE)
outdir <- if (length(args)) args[1] else "examples"
dir.create(outdir, showWarnings = FALSE, recursive = TRUE)
library(definetti); library(ggplot2)

# ---- simulated data --------------------------------------------------------
set.seed(42)
rdir <- function(n, alpha) { g <- matrix(rgamma(n * length(alpha), alpha), n, byrow = TRUE); g / rowSums(g) }
mk <- function(K, centers, n = 40) {
  out <- do.call(rbind, lapply(seq_along(centers), function(i) {
    m <- rdir(n, 25 * centers[[i]]); df <- as.data.frame(m)
    names(df) <- paste0("A", 1:K); df$pop <- paste0("Pop ", i); df }))
  out
}
d2 <- mk(2, list(c(.2,.8), c(.5,.5), c(.85,.15)))
d3 <- mk(3, list(c(.7,.2,.1), c(.15,.7,.15), c(.2,.2,.6)))
d4 <- mk(4, list(c(.6,.2,.1,.1), c(.1,.6,.2,.1), c(.1,.1,.6,.2), c(.2,.1,.1,.6)), n = 30)

sv <- function(p, f, w = 6.5, h = 5.5) ggsave(file.path(outdir, f), p, width = w, height = h, dpi = 150)
sv(definetti_plot(d2, c("A1","A2"), colour_by = "pop", title = "K = 2",
                  axis_titles = c("Frequency: A1", "Frequency: A2")), "k2.png", 7, 3.2)
sv(definetti_plot(d3, c("A1","A2","A3"), colour_by = "pop",
                  axis_titles = c("Frequency: A1", "Frequency: A2", "Frequency: A3"),
                  figure_number = 1, caption = "Individuals simulated from three Dirichlet populations; each point is one individual."),
   "k3.png")
gt <- data.frame(AA = c(.25,.04,.49,.0), Aa = c(.5,.32,.42,.3), aa = c(.25,.64,.09,.7),
                 t = c(1,1,1,1))
sv(definetti_plot(gt, c("AA","Aa","aa"), show_hw = TRUE, label_by = "t", base_size = 14,
                  title = "Genotype frequencies", legend_position = "none"), "k3_hw.png")
traj <- do.call(rbind, lapply(1:3, function(i) { p <- seq(.1, .9, length.out = 8)
  m <- cbind(p, (1-p)*(0.3+0.1*i), (1-p)*(0.7-0.1*i)); data.frame(m, id = i)}))
names(traj)[1:3] <- c("A1","A2","A3")
sv(definetti_plot(traj, c("A1","A2","A3"), connect_by = "id", colour_by = "id", shape_by = NULL,
                  legend_title = "Trajectory"), "k3_paths.png")
sv(definetti_plot(d4, paste0("A", 1:4), colour_by = "pop", view = c(25, 20)), "k4.png")
sv(definetti_plot(d4, paste0("A", 1:4), colour_by = "pop",
                  view = list(c(25, 20), c(115, 20), c(0, 85), c(205, -20)),
                  legend_position = "bottom"), "k4_views.png", 9, 8.5)
sv(definetti_plot(d4, paste0("A", 1:4), colour_component = "A4", vertex_labels = paste("Allele", 1:4),
                  axis_titles = paste("Frequency:", 1:4)), "k4_colour.png")
sv(definetti_plot(d3, c("A1","A2","A3"), colour_component = "A3", jitter_height = 0), "k3_colour.png", 7, 3.5)
sv(definetti_plot(d4, paste0("A", 1:4), colour_component = "A4", colour_range = c("lightgoldenrod1", "navy")), "k4_colour_range.png")
cat("examples written to", outdir, "\n")
