# Input:        None
# Output:       outdir/allele.freq_k2.csv       K=2: allele frequencies, 3 populations x 40 loci
#               outdir/genotype.freq_k3.csv     K=3: genotype freqs (AA, Aa, aa), drift trajectories
#               outdir/individuals.ancestry_k4.csv  K=4: ancestry fractions of individuals
#               outdir/data.summary.txt         row counts and column description
