args <- commandArgs(trailingOnly = TRUE)
outdir <- if (length(args)) args[1] else "inst/extdata"
dir.create(outdir, showWarnings = FALSE, recursive = TRUE)
set.seed(2026)
rdir <- function(n, alpha) { g <- matrix(rgamma(n * length(alpha), alpha), n, byrow = TRUE); g / rowSums(g) }
rnd <- function(df, cols, d = 4) { df[cols] <- lapply(df[cols], round, d); df }

# ---- K = 2: allele frequencies, 3 populations x 40 loci --------------------
f2 <- do.call(rbind, lapply(list(North = 0.25, Central = 0.5, South = 0.8), function(m) {
  p <- rbeta(40, 8 * m, 8 * (1 - m)); data.frame(locus = sprintf("L%02d", 1:40), p1 = p, p2 = 1 - p) }))
f2$population <- rep(c("North", "Central", "South"), each = 40)
f2 <- rnd(f2[, c("population", "locus", "p1", "p2")], c("p1", "p2"))
f2$p2 <- round(1 - f2$p1, 4)                       # keep exact sum to 1 after rounding
write.csv(f2, file.path(outdir, "allele.freq_k2.csv"), row.names = FALSE)

# ---- K = 3: genotype frequencies along drift trajectories ------------------
# Wright-Fisher drift, N = 50 diploids, random mating; start p = 0.3, 0.5, 0.7
g3 <- do.call(rbind, lapply(c(0.3, 0.5, 0.7), function(p0) {
  N <- 50; p <- p0; rows <- list()
  for (gen in 0:25) {
    gt <- rmultinom(1, N, c(p^2, 2 * p * (1 - p), (1 - p)^2))[, 1]
    rows[[gen + 1]] <- data.frame(start_p = p0, generation = gen,
                                  AA = gt[1] / N, Aa = gt[2] / N, aa = gt[3] / N)
    p <- (2 * gt[1] + gt[2]) / (2 * N)
  }
  do.call(rbind, rows) }))
g3$population <- paste0("Start p = ", g3$start_p)
g3 <- g3[, c("population", "generation", "AA", "Aa", "aa")]
write.csv(g3, file.path(outdir, "genotype.freq_k3.csv"), row.names = FALSE)

# ---- K = 4: ancestry fractions of individuals ------------------------------
cen <- list(Alpha = c(.80, .10, .05, .05), Beta = c(.05, .80, .10, .05),
            Gamma = c(.05, .05, .80, .10), Delta = c(.10, .05, .05, .80),
            Admixed = c(.30, .30, .20, .20))
q4 <- do.call(rbind, lapply(names(cen), function(nm) {
  n <- if (nm == "Admixed") 40 else 25
  q <- rdir(n, 20 * cen[[nm]]); colnames(q) <- paste0("Q", 1:4)
  data.frame(individual = sprintf("%s_%02d", nm, 1:n), group = nm, q) }))
q4[paste0("Q", 1:4)] <- round(q4[paste0("Q", 1:4)], 4)
q4$Q4 <- round(1 - q4$Q1 - q4$Q2 - q4$Q3, 4)       # exact sum to 1 after rounding
write.csv(q4, file.path(outdir, "individuals.ancestry_k4.csv"), row.names = FALSE)

# ---- self-check + summary (a check that can fail: reports max |rowsum - 1|) -
chk <- function(df, cols) max(abs(rowSums(df[cols]) - 1))
mx <- c(k2 = chk(f2, c("p1", "p2")), k3 = chk(g3, c("AA", "Aa", "aa")),
        k4 = chk(q4, paste0("Q", 1:4)))
cat(sprintf("max |row sum - 1|: k2 %.2g  k3 %.2g  k4 %.2g\n", mx[1], mx[2], mx[3]))
if (any(mx > 1e-6)) stop("example data rows do not sum to 1")
writeLines(c(
  "Simulated example data for the de Finetti vignette (definetti.make.data.R, seed 2026)",
  sprintf("allele.freq_k2.csv          %d rows: population, locus, p1, p2", nrow(f2)),
  sprintf("genotype.freq_k3.csv        %d rows: population, generation, AA, Aa, aa", nrow(g3)),
  sprintf("individuals.ancestry_k4.csv %d rows: individual, group, Q1..Q4", nrow(q4)),
  sprintf("max |row sum - 1|: k2 %.2g, k3 %.2g, k4 %.2g", mx[1], mx[2], mx[3])),
  file.path(outdir, "data.summary.txt"))
cat("wrote", outdir, "\n")
