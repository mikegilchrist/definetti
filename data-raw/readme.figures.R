library(definetti); library(ggplot2)
ext <- function(f) file.path("inst", "extdata", f)
f2 <- read.csv(ext("allele.freq_k2.csv")); g3 <- read.csv(ext("genotype.freq_k3.csv"))
q4 <- read.csv(ext("individuals.ancestry_k4.csv"))
out <- function(p, f, w = 6, h = 5) ggsave(file.path("man", "figures", f), p, width = w, height = h, dpi = 130)
grp <- c(Alpha = "#1b9e77", Beta = "#d95f02", Gamma = "#7570b3", Delta = "#e7298a", Admixed = "grey45")

# K = 2: finer ticks, labels every 0.25, larger translucent points, italic corners
out(definetti_plot(f2, c("p1", "p2"), colour_by = "population", point_size = 3.5, point_alpha = 0.5,
                   n_ticks = 20, label_at = c(0, .25, .5, .75, 1), jitter_height = 0.05, tick_offset = 0.09,
                   vertex_labels = c("Allele 1", "Allele 2"), vertex_label_face = "italic",
                   legend_title = "Population", base_size = 13), "readme_k2.png", 7, 3.4)

# K = 3: drift trajectories with arrows, Hardy-Weinberg curve, quarter gridlines, serif font
out(definetti_plot(g3, c("AA", "Aa", "aa"), colour_by = "population", connect_by = "population",
                   show_hw = TRUE, grid_at = c(.25, .5, .75), label_at = c(0, .25, .5, .75, 1),
                   point_size = 1.6, base_family = "serif", base_size = 13, legend_title = "Population",
                   axis_titles = c("Frequency: AA", "Frequency: Aa", "Frequency: aa")), "readme_k3_hw.png")

# K = 3: individuals, shape + colour, custom palette, no grid, grey frame, caption
q3 <- q4; q3[paste0("Q", 1:3)] <- q3[paste0("Q", 1:3)] / rowSums(q3[paste0("Q", 1:3)])
out(definetti_plot(q3, paste0("Q", 1:3), colour_by = "group", shape_by = "group", palette = grp,
                   show_grid = FALSE, frame_colour = "grey30", point_size = 2.6, point_alpha = 0.85,
                   vertex_labels = paste("Ancestry", 1:3), figure_number = 1,
                   caption = "Ancestry of 140 individuals, Q4 omitted and the rest rescaled to sum to 1.",
                   legend_position = "upper-left", legend_title = "Group", shape_title = "Group"), "readme_k3_shape.png")

# K = 4: gridlines drawn on the faces of the tetrahedron
out(definetti_plot(q4, paste0("Q", 1:4), colour_by = "group", palette = grp, view = c(25, 20),
                   face_grid = TRUE, grid_at = c(.25, .5, .75), grid_colour = "grey65",
                   vertex_labels = paste("Ancestry", 1:4), legend_position = "upper-left",
                   legend_title = "Group", point_size = 2.8), "readme_k4_facegrid.png", 6.5, 5.5)

# K = 4: four views side by side, no depth cue, no edge ticks, large clean labels
out(definetti_plot(q4, paste0("Q", 1:4), colour_by = "group", palette = grp,
                   view = list(c(25, 20), c(115, 20), c(0, 85), c(205, -20)),
                   depth_cue = FALSE, edge_ticks = FALSE, point_size = 1.8, point_alpha = 0.7,
                   vertex_label_size = 14, legend_position = "bottom", legend_title = "Group"),
    "readme_k4_views.png", 8, 7.5)

# K = 4: 4th component as colour, magma scale, bigger points, own title
out(definetti_plot(q4, paste0("Q", 1:4), colour_component = "Q4", colour_option = "magma",
                   point_size = 3.2, point_alpha = 0.9, show_grid = FALSE,
                   vertex_labels = paste("Ancestry", 1:4), legend_title = "Ancestry 4",
                   title = "Ancestry 4 shown as colour", base_size = 13), "readme_k4_colour.png")
cat("figures written to man/figures\n")
